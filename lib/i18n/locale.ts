import { getCurrentUser } from '@/lib/auth/current-user';
import type { Locale } from '@/lib/db/types';

/**
 * Язык интерфейса для серверного рендера.
 *
 * Раньше лежал в куке, но шлюз MIDAS снимает Set-Cookie с ответов, и выбор
 * не переживал перезагрузку. Теперь хранится в профиле (миграция 0004) —
 * сервер знает язык до первой отрисовки и перерисовывать текст на клиенте
 * не нужно.
 *
 * getCurrentUser() обёрнут в React.cache(), поэтому вызов отсюда не добавляет
 * похода в базу: layout и страница внутри него читают один и тот же результат.
 *
 * Исключение наружу не ловим намеренно. Без заголовка личности приложение
 * работать не может — но главное, этим же механизмом Next помечает страницу
 * динамической во время сборки, и перехват ломал бы сборку.
 */
export async function getLocale(): Promise<Locale> {
  return (await getCurrentUser()).locale;
}
