/**
 * Этап 8. Таймер обслуживания внутри процесса приложения.
 *
 * Планировщика MIDAS не даёт, но контейнер живёт постоянно: замер в
 * /api/health показал процесс с аптаймом в десятки минут, не перезапускаемый
 * между заходами. Значит, автопаузу и повторяющиеся правила можно выполнять
 * по времени, а не только при заходе человека на доску.
 *
 * Зачем, если ленивый вызов уже есть: без таймера задача, оставленная в
 * работе вечером пятницы, встала бы на паузу только в понедельник, когда
 * кто-нибудь откроет доску. Время считалось бы верно — пауза ставится задним
 * числом на пятничные 16:00, — но все выходные доска показывала бы задачу
 * «в работе». Таймер убирает этот разрыв.
 *
 * Ленивый вызов на доске остаётся: он подхватывает то, что таймер пропустил
 * при перезапуске или при деплое.
 *
 * register() вызывается Next один раз при старте сервера.
 */

// Раз в пять минут: отсечка в 16:00 и смена суток отрабатываются с запасом,
// а нагрузка — один короткий запрос с блокировкой, который почти всегда
// сразу видит «сегодня уже сделано» и выходит.
const EVERY_MS = 5 * 60 * 1000;

// Первый прогон не сразу: при деплое миграции уже прошли (они идут до
// server.js), но пусть сервер успеет подняться и начать отвечать.
const FIRST_RUN_DELAY_MS = 15 * 1000;

export async function register(): Promise<void> {
  // Edge-рантайм сюда тоже заходит, а pg там не работает.
  if (process.env.NEXT_RUNTIME !== 'nodejs') return;
  // Во время сборки базы нет — и обслуживать нечего.
  if (!process.env.DATABASE_URL) return;

  const { runDueMaintenance } = await import('@/lib/logic/maintenance');

  async function tick() {
    try {
      await runDueMaintenance();
    } catch {
      // Сбой обслуживания не должен ронять процесс: следующий тик через
      // пять минут, а до него работает ленивый вызов на доске.
    }
  }

  // unref: таймер не держит процесс при остановке контейнера.
  setTimeout(tick, FIRST_RUN_DELAY_MS).unref();
  setInterval(tick, EVERY_MS).unref();
}
